import Link from "next/link";
import type { MatchResult } from "@/lib/match/run";

/** The shareable result of a job-description match. */
export function MatchResultView({ result }: { result: MatchResult }) {
  const heading = [result.jobTitle, result.company]
    .filter(Boolean)
    .join(" at ");
  return (
    <article className="text-mist mx-auto flex max-w-3xl flex-col gap-10">
      <header className="flex flex-col gap-3">
        <p className="text-xs tracking-widest uppercase opacity-60">
          How my work fits this role
        </p>
        <h1
          className="hero-heading leading-none font-black tracking-tight uppercase"
          style={{ fontSize: "clamp(2rem, 6vw, 72px)" }}
        >
          {heading || "Role match"}
        </h1>
        <p className="text-lg leading-relaxed font-light">{result.summary}</p>
      </header>

      {result.topProjects.length > 0 && (
        <section aria-labelledby="m-projects" className="flex flex-col gap-4">
          <h2
            id="m-projects"
            className="text-sm font-medium tracking-widest uppercase opacity-70"
          >
            Most relevant projects
          </h2>
          <ol className="flex flex-col gap-3">
            {result.topProjects.map((p, i) => (
              <li
                key={p.slug}
                className="rounded-[28px] border-2 border-[#D7E2EA]/30 p-5 sm:p-6"
              >
                <p className="text-xs tracking-widest opacity-60">
                  {String(i + 1).padStart(2, "0")}
                </p>
                <Link
                  href={`/work/${p.slug}`}
                  className="text-xl font-medium underline-offset-4 hover:underline"
                >
                  {p.title}
                </Link>
                <p className="mt-1 opacity-80">{p.reason}</p>
              </li>
            ))}
          </ol>
        </section>
      )}

      {result.matchedSkills.length > 0 && (
        <section aria-labelledby="m-skills" className="flex flex-col gap-3">
          <h2
            id="m-skills"
            className="text-sm font-medium tracking-widest uppercase opacity-70"
          >
            Skills the role asks for that I have
          </h2>
          <ul className="flex flex-wrap gap-2">
            {result.matchedSkills.map((s) => (
              <li
                key={s}
                className="rounded-full border border-[#D7E2EA]/40 px-4 py-1.5 text-sm"
              >
                {s}
              </li>
            ))}
          </ul>
        </section>
      )}

      {result.gaps.length > 0 && (
        <section aria-labelledby="m-gaps" className="flex flex-col gap-3">
          <h2
            id="m-gaps"
            className="text-sm font-medium tracking-widest uppercase opacity-70"
          >
            Not covered by my work yet
          </h2>
          <ul className="list-disc pl-5 opacity-80">
            {result.gaps.map((g) => (
              <li key={g}>{g}</li>
            ))}
          </ul>
        </section>
      )}

      <footer className="flex flex-wrap items-center gap-4 border-t border-[#D7E2EA]/15 pt-6 text-sm">
        <Link
          href="/#contact"
          className="rounded-full border-2 border-[#D7E2EA] px-6 py-2.5 font-medium tracking-widest uppercase hover:bg-[#D7E2EA]/10"
        >
          Get in touch
        </Link>
        <span className="opacity-60">
          Generated by an AI from the content on this site. The job description
          was not saved.
        </span>
      </footer>
    </article>
  );
}
